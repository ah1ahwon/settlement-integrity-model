from m4 import *
def T(st_,amt=100,cum=0,ev=()): return {1:dict(m=0,amt=amt,st=st_,cum=cum,ev=list(ev)),9:dict(m=1,amt=50,st='C',cum=0,ev=[])}
KSET=[('L','L'),('LD','LD'),('LDB','LDB'),('LDBZ','LDBZ'),('LDBZ+X1','LDBZX'),('LDBZ+X2','LDBZY')]
I=[
 ('중복 청구','원장상 청구 완료(C) 건을 다시 10로 전송',T('C'),[(10,1,100)],1),
 ('구분 변경(10→20)','미청구(U) 건의 매출 10을 20로 바꿈',T('U'),[(20,1,100)],1),
 ('위조 취소(한도 이내)','승인되지 않은 취소 20(30)를 삽입',T('C'),[(20,1,30)],1),
 ('금액 변경(20)','승인된 취소 30을 20으로 변경',T('C',ev=[(30,False)]),[(20,1,20)],1),
 ('취소 재전송','이미 반영된 취소 30을 다시 전송',T('C',cum=30,ev=[(30,True)]),[(20,1,30)],1),
 ('누계 모호(세계 A: 2 반영)','반영 {2}, 미반영 {1,1}. 파일에 20(2)',T('C',cum=2,ev=[(1,False),(1,False),(2,True)]),[(20,1,2)],1),
 ('누계 모호(세계 B: 1+1 반영)','반영 {1,1}, 미반영 {2}. 파일에 20(2)',T('C',cum=2,ev=[(1,True),(1,True),(2,False)]),[(20,1,2)],1),
 ('취소 삭제 c=0','미반영 승인 취소 30이 파일에 없음',T('C',ev=[(30,False)]),[],0),
 ('취소 삭제 c=1','같은 파일, 취소 허용치 1',T('C',ev=[(30,False)]),[],1),
 ('거래 삭제 c=0','미청구(U) 건이 파일에 없음',T('U'),[],0),
 ('거래 삭제 c=1','같은 파일, 판매 허용치 1',T('U'),[],1),
]
print(f'{"변조 사례":28s}'+''.join(f'{n:>9s}' for n,_ in KSET)+'   (수락=정당 세계가 존재=구별 불가, 거절=식별)')
for nm,desc,led,rs,c in I:
    row=[]
    for _,k in KSET:
        row.append('수락' if explainable4((0,rs),led,set(k),c) else '거절')
    print(f'{nm:26s}'+''.join(f'{r:>10s}' for r in row)+'   '+desc)
# 정당 대조: 위 사례의 원래 정당 파일은 각 정보 조합에서 수락되는지(건전성)
print('\n정당 파일 확인(모두 수락이어야 함)')
L=[('취소 반영',T('C',ev=[(30,False)]),[(20,1,30)],1),('판매',T('U'),[(10,1,100)],1),('청구완료 취소 없음',T('C'),[],1)]
for nm,led,rs,c in L: print(' ',nm,[explainable4((0,rs),led,set(k),c) for _,k in KSET])
